drawFuncTexture proc
    push bp
    mov bp, sp
    xPos   equ [bp + 8]
    yPos   equ [bp + 6]
    add word ptr yPos, 2
    texPtr equ [bp + 4]
    ; only yPos because we need to do an entire row of pixels between texture and row
    shl word ptr yPos, 3
    shl word ptr xPos, 3
    sub sp, 4
    pusha 

    max_x equ [bp - sShapeLightIsh]
    max_y equ [bp - 4]

    mov ax, xPos
    add ax, 8
    mov max_x, ax
    mov ax, yPos
    add ax, 8
    mov max_y, ax

    mov si, texPtr          ; si = pointer to texture data (offset)
    mov dx, yPos
yLoop:
    mov cx, xPos
xLoop:
    ; calculate front buffer index
    push ax
    push cx
    push bx
    push dx
    push si

    mov bx, dx
    mov ax, dx
    shl ax, 8
    shl bx, 6
    add ax, bx
    add ax, cx
    mov di, ax              ; di = offset into frontBuffer

    mov al, [si]            ; read one byte from texture
    mov frontBuffer[di], al ; store it

    pop si
    pop dx
    pop bx
    pop cx
    pop ax

    inc si                  ; advance texture pointer
    inc cx
    cmp cx, max_x
    jnz xLoop

    inc dx
    cmp dx, max_y
    jnz yLoop

    popa
    add sp, 4
    pop bp
    ret 6                   ; clean stack of 3 arguments
drawFuncTexture endp
